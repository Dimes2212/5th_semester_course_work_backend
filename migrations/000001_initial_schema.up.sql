CREATE TABLE listings (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    author_id UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    category_id SMALLINT NOT NULL REFERENCES categories (id) ON DELETE RESTRICT,
    location_id SMALLINT NOT NULL REFERENCES locations (id) ON DELETE RESTRICT,
    location_details VARCHAR(150),
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('lost', 'found')),
    title VARCHAR(120) NOT NULL CHECK (btrim(title) <> ''),
    description TEXT NOT NULL DEFAULT '' CHECK (char_length(description) <= 2000),
    event_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'resolved', 'archived')),
    resolved_with_user_id UUID REFERENCES users (id) ON DELETE SET NULL,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (resolved_with_user_id IS NULL OR resolved_with_user_id <> author_id),
    CHECK (
        (status = 'resolved' AND resolved_at IS NOT NULL)
        OR
        (status <> 'resolved' AND resolved_at IS NULL AND resolved_with_user_id IS NULL)
    )
);

CREATE INDEX listings_author_id_idx ON listings (author_id);
CREATE INDEX listings_feed_idx ON listings (status, created_at DESC) WHERE deleted_at IS NULL;
CREATE INDEX listings_kind_status_created_at_idx ON listings (kind, status, created_at DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX listings_category_status_created_at_idx ON listings (category_id, status, created_at DESC)
    WHERE deleted_at IS NULL;
CREATE INDEX listings_location_status_created_at_idx ON listings (location_id, status, created_at DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE listing_photos (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id UUID NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    storage_key TEXT NOT NULL CHECK (btrim(storage_key) <> ''),
    position SMALLINT NOT NULL CHECK (position BETWEEN 1 AND 3),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (listing_id, position)
);

CREATE TABLE conversations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    listing_id UUID NOT NULL REFERENCES listings (id) ON DELETE CASCADE,
    initiator_id UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (listing_id, initiator_id)
);

CREATE INDEX conversations_initiator_id_idx ON conversations (initiator_id);
CREATE INDEX conversations_listing_id_idx ON conversations (listing_id);

CREATE TABLE messages (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    conversation_id UUID NOT NULL REFERENCES conversations (id) ON DELETE CASCADE,
    sender_id UUID NOT NULL REFERENCES users (id) ON DELETE RESTRICT,
    text TEXT NOT NULL CHECK (char_length(btrim(text)) BETWEEN 1 AND 2000),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    read_at TIMESTAMPTZ
);

CREATE INDEX messages_conversation_created_at_idx ON messages (conversation_id, created_at);
