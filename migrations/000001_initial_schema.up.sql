CREATE TABLE users (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    full_name VARCHAR(100) NOT NULL CHECK (btrim(full_name) <> ''),
    email VARCHAR(255) NOT NULL CHECK (email = lower(email)),
    password_hash TEXT NOT NULL CHECK (btrim(password_hash) <> ''),
    avatar_key TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX users_email_lower_uidx ON users (lower(email));

CREATE TABLE refresh_sessions (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id UUID NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash TEXT NOT NULL UNIQUE CHECK (btrim(token_hash) <> ''),
    device_name VARCHAR(100),
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    revoked_at TIMESTAMPTZ
);

CREATE INDEX refresh_sessions_user_id_idx ON refresh_sessions (user_id);

CREATE TABLE categories (
    id SMALLINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    slug VARCHAR(50) NOT NULL UNIQUE CHECK (slug ~ '^[a-z0-9_]+$'),
    name VARCHAR(100) NOT NULL UNIQUE CHECK (btrim(name) <> ''),
    position SMALLINT NOT NULL CHECK (position > 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

